// Generates THIRD_PARTY_NOTICES.md from the dependencies shipped in Oword builds:
// JavaScript runtime packages (npm, production only) and Rust crates compiled for macOS.
// Usage: npm run notices
import { execSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const root = join(dirname(new URL(import.meta.url).pathname), '..');
const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)([-._].*)?$/i;

function licenseTexts(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => ({ file: f, text: readFileSync(join(dir, f), 'utf8').trim() }));
}

// ---- JavaScript (bundled into the web/desktop frontend)
const js = execSync('npm ls --omit=dev --all --parseable', { cwd: root, encoding: 'utf8' })
  .trim().split('\n').slice(1)
  .map((dir) => {
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const license = typeof pkg.license === 'string' ? pkg.license : JSON.stringify(pkg.license ?? pkg.licenses ?? 'UNKNOWN');
    const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? '';
    return { name: pkg.name, version: pkg.version, license, repo, texts: licenseTexts(dir) };
  });
const seen = new Set();
const jsPkgs = js.filter((p) => !seen.has(p.name + p.version) && seen.add(p.name + p.version)).sort((a, b) => a.name.localeCompare(b.name));

// ---- Rust (compiled into the macOS app)
const meta = JSON.parse(execSync('cargo metadata --format-version 1 --locked --filter-platform aarch64-apple-darwin', {
  cwd: join(root, 'src-tauri'), encoding: 'utf8', maxBuffer: 64 * 1024 * 1024,
}));
const ids = new Set(meta.resolve.nodes.map((n) => n.id));
const rustPkgs = meta.packages
  .filter((p) => ids.has(p.id) && p.source)
  .map((p) => ({ name: p.name, version: p.version, license: p.license ?? 'UNKNOWN', repo: p.repository ?? '', texts: licenseTexts(dirname(p.manifest_path)) }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

// ---- Render; identical license texts are printed once and referenced afterwards.
const textIndex = new Map();
let out = `# Third-Party Notices

Oword itself is released under the MIT License (see [LICENSE](LICENSE)).
The distributed application includes the third-party software listed below, each under its own license.
Where a package offers a choice of licenses (for example "MIT OR Apache-2.0", or JSZip's "MIT OR GPL-3.0-or-later"),
Oword uses it under the MIT License.

Crates under MPL-2.0 (cssparser, cssparser-macros, dtoa-short, option-ext, selectors) are used unmodified;
their source code is available from crates.io and the repositories linked below.

This file is generated by \`npm run notices\`. Do not edit it by hand.

## Summary

| Ecosystem | Packages |
|---|---|
| JavaScript (npm, runtime) | ${jsPkgs.length} |
| Rust (crates.io, macOS build) | ${rustPkgs.length} |

`;

function section(title, pkgs) {
  out += `## ${title}\n\n| Package | Version | License |\n|---|---|---|\n`;
  for (const p of pkgs) out += `| ${p.repo ? `[${p.name}](${p.repo.replace(/^git\+/, '').replace(/\.git$/, '')})` : p.name} | ${p.version} | ${p.license} |\n`;
  out += '\n';
}
section('JavaScript packages', jsPkgs);
section('Rust crates', rustPkgs);

out += '## License texts\n\n';
for (const p of [...jsPkgs, ...rustPkgs]) {
  out += `### ${p.name} ${p.version}\n\nLicense: ${p.license}\n\n`;
  if (!p.texts.length) { out += '_No license file is shipped with this package; see the license identifier above._\n\n'; continue; }
  for (const t of p.texts) {
    const prev = textIndex.get(t.text);
    if (prev) { out += `${t.file}: identical to the text under ${prev}.\n\n`; continue; }
    textIndex.set(t.text, `${p.name} ${p.version} (${t.file})`);
    out += `<details><summary>${t.file}</summary>\n\n\`\`\`text\n${t.text.replace(/```/g, "'''")}\n\`\`\`\n\n</details>\n\n`;
  }
}

writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), out);
console.log(`THIRD_PARTY_NOTICES.md: ${jsPkgs.length} npm packages, ${rustPkgs.length} crates, ${textIndex.size} distinct license texts`);
